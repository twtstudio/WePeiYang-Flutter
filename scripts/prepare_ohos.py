"""Prepare the Flutter OHOS dependency overlay from a resolved Flutter project."""

import argparse
import json
import re
import shutil
from pathlib import Path
from urllib.parse import urljoin, urlparse
from urllib.request import url2pathname


ROOT = Path(__file__).resolve().parents[1]
PACKAGE_CONFIG = ROOT / ".dart_tool/package_config.json"
OVERRIDES = ROOT / "pubspec_overrides.yaml"
PATCH_DIR = ROOT / ".dart_tool/ohos/flutter_math_fork"
MARKER = "# Generated by scripts/prepare_ohos.py"
PATCH_FILES = {
    "lib/src/render/layout/line_editable.dart": 1,
    "lib/src/widgets/selectable.dart": 2,
    "lib/src/widgets/selection/gesture_detector_builder_selectable.dart": 1,
}
WINDOWS_CASE = re.compile(r"^(\s*)case TargetPlatform\.windows:", re.MULTILINE)


def find_math_package() -> Path:
    packages = json.loads(PACKAGE_CONFIG.read_text(encoding="utf-8"))["packages"]
    package = next(item for item in packages if item["name"] == "flutter_math_fork")
    uri = urlparse(urljoin(PACKAGE_CONFIG.as_uri(), package["rootUri"]))
    if uri.scheme != "file":
        raise ValueError("flutter_math_fork must resolve to a local directory")
    return Path(url2pathname(uri.path))


def inherited_overrides() -> str:
    pubspec = (ROOT / "pubspec.yaml").read_text(encoding="utf-8")
    header = re.search(r"(?m)^dependency_overrides:[ \t]*$", pubspec)
    if not header:
        return ""
    tail = pubspec[header.end():].lstrip("\n")
    block = re.split(r"(?m)^[a-zA-Z_]\w*:", tail, maxsplit=1)[0]
    return block.rstrip() + "\n"


def prepare() -> None:
    if OVERRIDES.exists() and not OVERRIDES.read_text(encoding="utf-8").startswith(MARKER):
        raise ValueError("Keep your existing pubspec_overrides.yaml and add the OHOS override to it manually")
    source = find_math_package()
    if source.resolve() != PATCH_DIR.resolve():
        shutil.copytree(source, PATCH_DIR, dirs_exist_ok=True)
    for name, expected in PATCH_FILES.items():
        original = (source / name).read_text(encoding="utf-8")
        patched, count = WINDOWS_CASE.subn(r"\1default:", original)
        if source.resolve() == PATCH_DIR.resolve() and count == 0:
            continue
        if count != expected:
            raise ValueError(f"Review platform handling in {name} for this flutter_math_fork version")
        (PATCH_DIR / name).write_text(patched, encoding="utf-8")
    OVERRIDES.write_text(
        f"{MARKER}\ndependency_overrides:\n"
        f"{inherited_overrides()}"
        "  flutter_math_fork:\n    path: .dart_tool/ohos/flutter_math_fork\n",
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--clear", action="store_true", help="Remove the generated overlay.")
    args = parser.parse_args()
    try:
        if args.clear:
            if OVERRIDES.exists() and OVERRIDES.read_text(encoding="utf-8").startswith(MARKER):
                OVERRIDES.unlink()
        else:
            prepare()
    except (OSError, ValueError, StopIteration) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
